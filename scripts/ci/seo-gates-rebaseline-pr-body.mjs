#!/usr/bin/env node
/**
 * seo-gates-rebaseline-pr-body.mjs — render the PR body of the safe-rebaseline
 * PR opened by `cathedral-seo-gates-check.yml`.
 *
 * It lives in a script rather than in a YAML heredoc for one reason: the body
 * must carry both `## Implementato` and `## Non implementato (ancora)`
 * verbatim (AGENTS.md #8, enforced by `pr-body-contract.yml`), and a heredoc
 * inside a `run:` block is the one place where those headers are neither
 * linted nor unit-testable. Here they are both.
 *
 * Usage:
 *   node scripts/ci/seo-gates-rebaseline-pr-body.mjs \
 *     --report=<path> --files="a.json b.json" --run-url=<url> > body.md
 */

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * @param {{report?: string, files?: string, runUrl?: string}} input
 * @returns {string}
 */
export function renderPrBody({ report = '', files = '', runUrl = '' }) {
  const applied = files.trim().split(/\s+/).filter(Boolean);
  const refused = /— REFUSED/.test(report);

  const lines = [];
  if (runUrl) lines.push(`Auto-generated by [workflow run](${runUrl}).`, '');
  lines.push('## Implementato');
  lines.push(
    '- Rebaseline dei gate SEO migliorati, applicato solo dove `scripts/ci/lib/baseline-ratchet.mjs` ha dimostrato che il nuovo file è più STRETTO del committato: nessun bucket allentato, corpus misurato non ristretto.',
  );
  for (const file of applied) lines.push(`- \`${file}\` aggiornato con la misura corrente.`);
  if (report.trim()) lines.push('', report.trim());
  lines.push('');
  lines.push('## Non implementato (ancora)');
  if (refused) {
    lines.push(
      "- Gate elencati come `REFUSED` qui sopra: la baseline committata è stata ripristinata byte per byte — `blocked: il file rigenerato allentava almeno un bucket, o il corpus misurato si è ristretto oltre la soglia`.",
    );
  } else {
    lines.push(
      '- Nessun residuo: ogni gate migliorato di questa run ha passato il ratchet ed è nel diff — `by construction`.',
    );
  }
  return lines.join('\n') + '\n';
}

const __filename = fileURLToPath(import.meta.url);
if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === __filename) {
  const args = new Map(
    process.argv.slice(2).map((a) => {
      const [k, ...rest] = a.replace(/^--/, '').split('=');
      return [k, rest.join('=')];
    }),
  );
  const reportPath = args.get('report');
  let report = '';
  if (reportPath) {
    try {
      report = readFileSync(reportPath, 'utf8');
    } catch {
      report = '';
    }
  }
  process.stdout.write(
    renderPrBody({
      report,
      files: args.get('files') ?? '',
      runUrl: args.get('run-url') ?? '',
    }),
  );
}
