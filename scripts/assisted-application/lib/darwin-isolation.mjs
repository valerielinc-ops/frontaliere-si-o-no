/** Private per-job homes and nested browser permissions; never inherit the manager's secrets. */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const execute = promisify(execFile);
const quote = value => JSON.stringify(fs.realpathSync(value));
const SYSTEM_READS = ['/System', '/usr', '/bin', '/sbin', '/Library', '/dev', '/private/var/db', '/private/etc', '/Applications'].filter(value => fs.existsSync(value));
const base = () => `(version 1)\n(deny default)\n(allow process*)\n(allow sysctl-read)\n(allow mach-lookup)\n(allow file-read-metadata)\n(allow network-outbound)\n${SYSTEM_READS.map(value => `(allow file-read* (subpath ${quote(value)}))`).join('\n')}\n`;

export function privateBrowserEnvironment({ home, temporary, env = process.env }) {
  return { PATH: '/usr/bin:/bin', HOME: home, TMPDIR: temporary,
    ...Object.fromEntries(['LANG', 'LC_ALL', 'TZ', 'DISPLAY', 'XAUTHORITY'].filter(key => env[key]).map(key => [key, env[key]])) };
}

export async function createDarwinIsolation({ jobRoot, releaseRoot, dependencyRoot, credentialsPath, brokerSocket,
  chromiumPath, node = process.execPath }) {
  if (process.platform !== 'darwin') throw new Error('execution_isolation_platform');
  for (const relative of ['home', 'documents', 'browser', 'browser/home', 'browser/profile']) fs.mkdirSync(path.join(jobRoot, relative), { recursive: true, mode: 0o700 });
  const documents = path.join(jobRoot, 'documents'); const browserRoot = path.join(jobRoot, 'browser');
  const nodeDirectory = path.dirname(fs.realpathSync(node));
  const browserBundle = /^(.*\.app)(?:\/|$)/.exec(chromiumPath)?.[1] || path.dirname(chromiumPath);
  const agentProfile = `${base()}\n(allow file-read* (subpath ${quote(releaseRoot)}) (subpath ${quote(dependencyRoot)}) (subpath ${quote(nodeDirectory)}) (subpath ${quote(browserBundle)}))
(allow file-read* file-write* (subpath ${quote(jobRoot)}))
(allow file-read* (literal ${quote(credentialsPath)}))
(allow file-read* file-write* (literal ${quote(brokerSocket)}))\n`;
  const browserProfile = `${base()}\n(allow file-read* (subpath ${quote(browserBundle)}) (subpath ${quote(path.join(jobRoot, 'nopecha'))}) (subpath ${quote(documents)}))
(allow file-read* file-write* (subpath ${quote(browserRoot)}))\n`;
  const agentProfilePath = path.join(jobRoot, 'agent.sb'); const browserProfilePath = path.join(jobRoot, 'browser.sb');
  fs.writeFileSync(agentProfilePath, agentProfile, { mode: 0o600 }); fs.writeFileSync(browserProfilePath, browserProfile, { mode: 0o600 });
  // Canaries are outside every allowed subtree. Both profiles must read a
  // positive control and reject this file, before the agent sees a credential.
  const canaryRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'execution-owner-canary-')); fs.chmodSync(canaryRoot, 0o700);
  const canary = path.join(canaryRoot, 'private.txt'); fs.writeFileSync(canary, 'owner-home-must-not-be-readable', { mode: 0o600 });
  const readable = path.join(documents, 'readable.txt'); fs.writeFileSync(readable, 'job-readable', { mode: 0o600 });
  try {
    for (const profile of [agentProfilePath, browserProfilePath]) {
      const env = privateBrowserEnvironment({ home: path.join(browserRoot, 'home'), temporary: browserRoot });
      const control = await execute('/usr/bin/sandbox-exec', ['-f', profile, '/bin/cat', readable], { env, timeout: 10_000 });
      if (control.stdout !== 'job-readable') throw new Error('execution_isolation_positive_failed');
      let denied = false;
      try { await execute('/usr/bin/sandbox-exec', ['-f', profile, '/bin/cat', canary], { env, timeout: 10_000 }); }
      catch (error) { denied = !String(error.stdout || '').includes('owner-home-must-not-be-readable'); }
      if (!denied) throw new Error('execution_isolation_owner_read_allowed');
    }
  } finally { fs.rmSync(canaryRoot, { recursive: true, force: true }); fs.rmSync(readable, { force: true }); }
  const launcher = path.join(jobRoot, 'browser-launch.sh');
  // Paths are generated by this manager, never derived from employer content.
  const shellQuote = value => `'${value.replace(/'/g, `'\\''`)}'`;
  fs.writeFileSync(launcher, `#!/bin/sh\nexec /usr/bin/sandbox-exec -f ${shellQuote(browserProfilePath)} ${shellQuote(chromiumPath)} "$@"\n`, { mode: 0o700 });
  return { agentProfile: agentProfilePath, browserLauncher: launcher, browserRoot, documents,
    browserHome: path.join(browserRoot, 'home'), browserProfile: path.join(browserRoot, 'profile'), home: path.join(jobRoot, 'home') };
}
