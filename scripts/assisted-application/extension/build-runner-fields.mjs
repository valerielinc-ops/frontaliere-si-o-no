/**
 * Writes extension/runner-fields.js: the portal runner's own field reading
 * (lib/portal/fields.mjs `extractFieldsInPage`, self-contained by design) as
 * a classic script the extension injects before its engine. The extension
 * then names every field exactly as the runner recorded it in the order's
 * `portalAnswers`, on any portal, so the runner's answers match by
 * construction (owner request 2026-10-01: generic, not per site).
 *
 *   node scripts/assisted-application/extension/build-runner-fields.mjs
 *
 * tests/assisted-application-fill-extension.test.ts fails when the file and
 * fields.mjs drift.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { extractFieldsInPage } from '../lib/portal/fields.mjs';

export const RUNNER_FIELDS_PATH = fileURLToPath(new URL('./runner-fields.js', import.meta.url));

export function renderRunnerFields() {
  return `// Generated by build-runner-fields.mjs from scripts/assisted-application/lib/portal/fields.mjs.
// Do not edit: run \`node scripts/assisted-application/extension/build-runner-fields.mjs\`.
(function (root) {
  'use strict';
  root.CompilaRunnerFields = ${extractFieldsInPage.toString()};
})(globalThis);
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    // The committed file must be what fields.mjs renders today.
    const current = await readFile(RUNNER_FIELDS_PATH, 'utf8').catch(() => '');
    if (current !== renderRunnerFields()) {
      console.error('runner-fields.js is out of date: node scripts/assisted-application/extension/build-runner-fields.mjs');
      process.exit(1);
    }
    console.log('runner-fields.js up to date');
  } else {
    await writeFile(RUNNER_FIELDS_PATH, renderRunnerFields());
    console.log(`wrote ${RUNNER_FIELDS_PATH}`);
  }
}
