/**
 * Provenance predicates for source-owned JobPosting values, shared by the
 * builder (build-plugins/shared/jobPostingSchema.ts) and the audit that checks
 * its output against data/jobs.json (scripts/validate-jobs-rich-results-sample.mjs).
 *
 * Owner decision 2026-10-31: keep JobPosting field coverage while improving
 * data quality. Shared predicates distinguish a real source street/deadline
 * from weak values and placeholders; producer and observer use the same rules.
 */

/**
 * Only a salary the listing (or the employer, for publisher ads) reported.
 * `estimated` is the sector band of the crawler pipeline; `existing` and a
 * missing value are structured salaries of unknown origin — the job cards
 * already label them "fonte non verificata" (build-plugins/shared/
 * salaryEstimateSuffix.ts), so they do not become employer statements here.
 *
 * @param {{ salarySource?: unknown } | null | undefined} job
 */
export function isSalaryReportedBySource(job) {
  return String(job?.salarySource ?? '').trim().toLowerCase() === 'reported';
}

const STREET_KEYWORD_RE = /\b(?:via|viale|vicolo|vicoletto|piazza|piazzale|piazzetta|corso|strada|stradone|salita|sentiero|contrada|largo|riva|lungolago|rampa|passaggio|rue|route|chemin|avenue|place|quai|boulevard|impasse|ruelle|sentier|allée)\b|(?:strasse|straße|weg|platz|gasse|allee)\b/i;

/**
 * Does the source value read as a street of the locality, rather than a city,
 * a region or a crawler artefact? Crawler/enrichment pipelines have stored the
 * locality itself as `streetAddress` ("Lugano"), and scraped navigation text.
 *
 * @param {unknown} raw source streetAddress
 * @param {unknown} locality the emitted addressLocality
 */
export function isSourceStreetAddress(raw, locality) {
  const street = String(raw ?? '').trim();
  if (street.length < 3 || street.length > 100) return false;
  if ((street.match(/\s/g) || []).length > 8) return false;
  if (/stampa|segnalazione|descrizione|annuncio|verifica|attività|dillo/i.test(street)) return false;
  const fold = (value) => String(value ?? '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
  if (fold(street) === fold(locality)) return false;
  if (isPlaceholderStreetAddress(street)) return false;
  if (!/[a-zà-ÿ]/i.test(street)) return false;
  return /\d/.test(street) || STREET_KEYWORD_RE.test(street);
}

const CITY_CENTRE_PLACEHOLDER_RE = /(?:\bcity\s+cent(?:re|er)|\bstadtzentrum|\bzentrum|\bcentre[-\s]ville|\bcentro)\s*$/i;

/**
 * "<city> city centre" and its translations: text generated by an old fallback
 * of the builder, never a street. "Via Centro 5" and "Via Centro" are real
 * streets, hence the street-keyword exclusion.
 *
 * @param {unknown} raw
 */
export function isPlaceholderStreetAddress(raw) {
  const street = String(raw ?? '').trim();
  return CITY_CENTRE_PLACEHOLDER_RE.test(street) && !STREET_KEYWORD_RE.test(street);
}

/**
 * The furthest a source date can sit and still read as an application
 * deadline. ATS exports fill the field with a system default: PwC ships
 * today + 10 years on every row, others + 2 years.
 */
export const SOURCE_DEADLINE_MAX_DAYS = 365;

/**
 * The listing's own application deadline as an ISO string, or null when the
 * source has none or the value is a system default rather than a deadline. A
 * past date stays: it is true, and it is what closes an archived posting.
 *
 * @param {unknown} raw source validThrough
 * @param {Date} [now]
 * @returns {string | null}
 */
export function resolveSourceDeadline(raw, now = new Date()) {
  if (!raw) return null;
  const deadline = new Date(String(raw));
  if (Number.isNaN(deadline.getTime())) return null;
  const clock = Number.isFinite(now?.getTime()) ? now : new Date();
  const days = (deadline.getTime() - clock.getTime()) / 86_400_000;
  return days > SOURCE_DEADLINE_MAX_DAYS ? null : deadline.toISOString();
}

const ON_SITE_OR_HYBRID_RE = /(?:^|[^\p{L}\p{N}])(?:on[-\s]?site|vor\s+ort|in\s+sede|in\s+presenza|sur\s+site|hybrid|hybride|ibrid[oa])(?![\p{L}\p{N}])/iu;
const FULLY_REMOTE_PHRASE_RE = /(?:^|[^\p{L}\p{N}])(?:100\s*%\s*(?:remote|remoto|home[-\s]?office|telelavoro|t[ée]l[ée]travail)|(?:fully|full|completely|entirely)[-\s]remote|remote[-\s]only|vollst[äa]ndig\s+remote)(?![\p{L}\p{N}])/iu;
const WORK_MODE_LABEL_RE = /^(?:remote|remoto|da\s+remoto|home[-\s]?office|telelavoro|telearbeit|t[ée]l[ée]travail|smart[-\s]?working|work\s+from\s+home)$/iu;

function hasWorkModeLabel(text) {
  return text.split(/\s*[|()[\],/;:·•]+\s*|\s+[-–—]\s+/u).some((part) => WORK_MODE_LABEL_RE.test(part.trim()));
}

/**
 * True only when the title or the location declares the job fully remote.
 * `TELECOMMUTE` tells Google the post needs no presence at all, so the old
 * test over the whole description was wrong twice: benefits such as "home
 * office possible" and "hybrid", or a "remote hands" duty, marked on-site jobs
 * as remote. "Remote" must be a label of its own ("Data Engineer (Remote)",
 * location "Remote, Switzerland"), not part of a role name.
 *
 * @param {{ title?: unknown, location?: unknown }} listing
 */
export function isFullyRemoteListing({ title, location } = {}) {
  const fields = [String(title ?? ''), String(location ?? '')];
  if (fields.some((text) => ON_SITE_OR_HYBRID_RE.test(text))) return false;
  return fields.some((text) => FULLY_REMOTE_PHRASE_RE.test(text) || hasWorkModeLabel(text));
}
