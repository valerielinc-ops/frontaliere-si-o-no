/**
 * Canton of a WGS84 point, offline and deterministic (P9a, 2026-10-05).
 *
 * Why. The events dataset carried 1285 events (2026-10-03 snapshot) with an
 * empty `canton`, 1284 of them WITH coordinates: the text matcher
 * (`resolveComuneNationwide`) found no BFS comune name in venue/title
 * ("Mitlödi", "Altdorf", "Petersplatz" are localities, not municipality
 * names), and the Nominatim pass that could fix them runs only inside the
 * MySwitzerland crawler, budgeted at a few hundred lookups per run — and
 * never when that crawler fails, as it has since 2026-10-04. Point-in-polygon
 * on the official canton boundaries answers the same question without any
 * network call, in the assembler, for every source.
 *
 * Data: `data/swiss-canton-boundaries.json`, generated by
 * `scripts/generate-swiss-canton-boundaries.mjs` from swisstopo
 * swissBOUNDARIES3D (layer `ch.swisstopo.swissboundaries3d-kanton-flaeche.fill`),
 * simplified with a declared tolerance (see the file's `simplification`).
 * Rings are flat `[lng0, lat0, lng1, lat1, …]` arrays; the first ring of each
 * polygon is the outer boundary, the following ones are holes (Campione
 * d'Italia inside TI, the Appenzell Innerrhoden enclaves inside AR, …).
 *
 * Contract — unknown stays unknown:
 *   - a point inside exactly ONE canton → that canton's BFS code;
 *   - a point outside every canton (Liechtenstein, Konstanz, Campione, a lake
 *     outside the cantonal surface) → null, never the nearest canton;
 *   - a point inside TWO cantons (a sliver where the simplified shared border
 *     overlaps, i.e. within the simplification tolerance of the real border)
 *     → null: ambiguous is not a guess;
 *   - a point exactly ON a ring edge (outer or hole) → null: ray casting would
 *     pick a side arbitrarily, so the boundary itself counts as ambiguous.
 */

import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const SWISS_CANTON_BOUNDARIES_PATH = path.join(__dirname, '..', '..', 'data', 'swiss-canton-boundaries.json');

/** Bounding box of a flat ring: [minLng, minLat, maxLng, maxLat]. */
function ringBbox(ring) {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (let i = 0; i < ring.length; i += 2) {
    const x = ring[i];
    const y = ring[i + 1];
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return [minX, minY, maxX, maxY];
}

/** True when (x, y) lies on a segment of the flat ring (collinear and within its extent). */
function pointOnRingBoundary(x, y, ring) {
  const n = ring.length;
  for (let i = 0, j = n - 2; i < n; j = i, i += 2) {
    const xi = ring[i];
    const yi = ring[i + 1];
    const xj = ring[j];
    const yj = ring[j + 1];
    const cross = (x - xj) * (yi - yj) - (y - yj) * (xi - xj);
    if (Math.abs(cross) > 1e-12) continue;
    if (x >= Math.min(xi, xj) && x <= Math.max(xi, xj) && y >= Math.min(yi, yj) && y <= Math.max(yi, yj)) return true;
  }
  return false;
}

/** Even-odd ray casting on a flat ring. */
function pointInRing(x, y, ring) {
  let inside = false;
  const n = ring.length;
  for (let i = 0, j = n - 2; i < n; j = i, i += 2) {
    const xi = ring[i];
    const yi = ring[i + 1];
    const xj = ring[j];
    const yj = ring[j + 1];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/**
 * Validate and index a boundaries document once: per canton, its polygons
 * with the outer ring's bbox (a cheap reject before ray casting).
 * Throws on a malformed document — a broken table must fail loudly, not
 * silently attribute nothing.
 */
export function indexCantonBoundaries(doc) {
  const cantons = doc?.cantons;
  if (!cantons || typeof cantons !== 'object') {
    throw new Error('swiss-canton-boundaries: missing `cantons` object');
  }
  const index = [];
  for (const [code, polygons] of Object.entries(cantons)) {
    if (!/^[A-Z]{2}$/.test(code) || !Array.isArray(polygons) || polygons.length === 0) {
      throw new Error(`swiss-canton-boundaries: invalid entry for canton ${code}`);
    }
    for (const polygon of polygons) {
      if (!Array.isArray(polygon) || polygon.length === 0) {
        throw new Error(`swiss-canton-boundaries: empty polygon for canton ${code}`);
      }
      for (const ring of polygon) {
        if (!Array.isArray(ring) || ring.length < 8 || ring.length % 2 !== 0 || !ring.every(Number.isFinite)) {
          throw new Error(`swiss-canton-boundaries: malformed ring for canton ${code}`);
        }
      }
      index.push({ code, bbox: ringBbox(polygon[0]), outer: polygon[0], holes: polygon.slice(1) });
    }
  }
  return index;
}

let defaultIndex = null;

function loadDefaultIndex() {
  if (!defaultIndex) {
    defaultIndex = indexCantonBoundaries(JSON.parse(readFileSync(SWISS_CANTON_BOUNDARIES_PATH, 'utf8')));
  }
  return defaultIndex;
}

/**
 * BFS code of the single canton containing `{lat, lng}`, or null (outside
 * every canton, ambiguous, or not a finite coordinate pair). `index` is
 * injectable for tests (`indexCantonBoundaries(fixtureDoc)`).
 */
export function cantonAtPoint(geo, index = loadDefaultIndex()) {
  const lat = geo?.lat;
  const lng = geo?.lng;
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null;
  const hits = new Set();
  for (const { code, bbox, outer, holes } of index) {
    if (lng < bbox[0] || lng > bbox[2] || lat < bbox[1] || lat > bbox[3]) continue;
    if (pointOnRingBoundary(lng, lat, outer) || holes.some((hole) => pointOnRingBoundary(lng, lat, hole))) return null;
    if (!pointInRing(lng, lat, outer)) continue;
    if (holes.some((hole) => pointInRing(lng, lat, hole))) continue;
    hits.add(code);
  }
  return hits.size === 1 ? [...hits][0] : null;
}
