#!/usr/bin/env node
/**
 * Refresh the BFS healthcare-sector wage table inlined in
 * build-plugins/shared/healthSectorWageBenchmark.ts.
 *
 * Source: BFS STAT-TAB (PxWeb API, free, no key), cube px-x-0304010000_201,
 * Wirtschaftsabteilung 86 "Gesundheitswesen", Berufliche Stellung and
 * Geschlecht total, percentiles P25 / median / P75 for Switzerland and the
 * seven Grossregionen. The LSE wave is biennial; run on each new wave:
 *
 *   node scripts/update-bfs-health-sector-wages.mjs           # check only
 *   node scripts/update-bfs-health-sector-wages.mjs --write   # rewrite table
 *   node scripts/update-bfs-health-sector-wages.mjs --year 2026 --write
 *
 * Check mode exits 1 when the committed literals differ from STAT-TAB. After
 * `--write` with a new year, also bump HEALTH_SECTOR_WAGE_SOURCE.waveYear and
 * databaseState in the same module.
 */

import fs from 'node:fs';
import np from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = np.dirname(fileURLToPath(import.meta.url));
const TARGET = np.resolve(__dirname, '..', 'build-plugins', 'shared', 'healthSectorWageBenchmark.ts');
const ENDPOINT = 'https://www.pxweb.bfs.admin.ch/api/v1/de/px-x-0304010000_201/px-x-0304010000_201.px';

// BFS Grossregion code -> key used by cantonSalaryIndex.ts.
const REGIONS = [
  ['-1', 'switzerland'],
  ['1', 'lemanique'],
  ['2', 'mittelland'],
  ['3', 'nordwest'],
  ['4', 'zurich'],
  ['5', 'ostschweiz'],
  ['6', 'zentral'],
  ['7', 'ticino'],
];
// Percentile code -> field.
const PERCENTILES = [['3', 'p25'], ['1', 'median'], ['4', 'p75']];

const args = process.argv.slice(2);
const write = args.includes('--write');
const yearIdx = args.indexOf('--year');
const source = fs.readFileSync(TARGET, 'utf8');
const committedYear = Number(/waveYear:\s*(\d{4})/.exec(source)?.[1]);
const year = yearIdx >= 0 ? String(args[yearIdx + 1]) : String(committedYear);

const query = {
  query: [
    { code: 'Jahr', selection: { filter: 'item', values: [year] } },
    { code: 'Grossregion', selection: { filter: 'item', values: REGIONS.map(([c]) => c) } },
    { code: 'Wirtschaftsabteilung', selection: { filter: 'item', values: ['86'] } },
    { code: 'Berufliche Stellung', selection: { filter: 'item', values: ['-1'] } },
    { code: 'Geschlecht', selection: { filter: 'item', values: ['-1'] } },
    { code: 'Zentralwert und andere Perzentile', selection: { filter: 'item', values: PERCENTILES.map(([c]) => c) } },
  ],
  response: { format: 'json-stat2' },
};

const res = await fetch(ENDPOINT, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify(query),
});
if (!res.ok) {
  console.error(`STAT-TAB ${res.status} ${res.statusText}`);
  process.exit(2);
}
const cube = await res.json();

// json-stat2: values are row-major over `id`, sized by `size`.
const dims = cube.id;
const index = (dim) => cube.dimension[dim].category.index;
function valueAt(coords) {
  let offset = 0;
  for (let i = 0; i < dims.length; i++) {
    const pos = index(dims[i])[coords[dims[i]]];
    offset = offset * cube.size[i] + pos;
  }
  return cube.value[offset];
}

const table = {};
for (const [regionCode, key] of REGIONS) {
  const row = {};
  for (const [pCode, field] of PERCENTILES) {
    const v = valueAt({
      Jahr: year,
      Grossregion: regionCode,
      Wirtschaftsabteilung: '86',
      'Berufliche Stellung': '-1',
      Geschlecht: '-1',
      'Zentralwert und andere Perzentile': pCode,
    });
    if (typeof v !== 'number' || !Number.isFinite(v)) {
      console.error(`missing value: year ${year}, region ${key}, ${field} (status: ${JSON.stringify(cube.status ?? null)})`);
      process.exit(2);
    }
    row[field] = Math.round(v);
  }
  table[key] = row;
}

const block = [
  '// BEGIN-BFS-HEALTH-WAGES (generated by scripts/update-bfs-health-sector-wages.mjs)',
  'export const HEALTH_SECTOR_MONTHLY_WAGES: Readonly<Record<Grossregion | \'switzerland\', MonthlyWageQuartiles>> = {',
  ...REGIONS.map(([, key]) => `  ${key}: { p25: ${table[key].p25}, median: ${table[key].median}, p75: ${table[key].p75} },`),
  '};',
  '// END-BFS-HEALTH-WAGES',
].join('\n');

const re = /\/\/ BEGIN-BFS-HEALTH-WAGES[\s\S]*?\/\/ END-BFS-HEALTH-WAGES/;
const current = re.exec(source)?.[0];
if (!current) {
  console.error(`marker block not found in ${TARGET}`);
  process.exit(2);
}

console.log(`LSE ${year}, NOGA 86, monthly gross CHF (P25 / median / P75):`);
for (const [, key] of REGIONS) console.log(`  ${key.padEnd(12)} ${table[key].p25} / ${table[key].median} / ${table[key].p75}`);

if (current === block) {
  console.log('✓ committed table matches STAT-TAB');
  process.exit(0);
}
if (write) {
  fs.writeFileSync(TARGET, source.replace(re, block));
  console.log(`✎ rewrote ${np.relative(process.cwd(), TARGET)}`);
  if (Number(year) !== committedYear) console.log(`  bump HEALTH_SECTOR_WAGE_SOURCE.waveYear to ${year} and databaseState by hand`);
  process.exit(0);
}
console.error('✖ committed table differs from STAT-TAB — rerun with --write');
process.exit(1);
