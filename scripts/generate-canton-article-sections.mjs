#!/usr/bin/env node
/**
 * Genera `packages/articles/engine/shared/cantonArticleSectionCore.generated.mjs`:
 * le 24 sezioni articoli cantonali (22 cantoni + i gruppi URL APPENZELLO e
 * BASILEA) come voci della stessa tabella di `articleSectionCore.mjs`.
 *
 * Perche' un file generato e non una lettura del JSON a runtime: il core deve
 * restare puro (niente `fs` ne' import JSON), perche' lo caricano sia Vite sia
 * `node` senza loader e, dopo il mirror dell'engine, anche il corpus, che non ha
 * `data/canton-url-slugs.json` nello stesso posto. La sorgente dei nomi resta
 * una sola: questo script la traduce in un modulo `.mjs` statico e `--check`
 * impedisce che i due divergano in silenzio
 * (`tests/build-plugins/cantonArticleSectionCore.test.ts`).
 *
 * Le voci sono INATTIVE: `ACTIVE_CANTON_SECTIONS` (sotto) e' la lista di
 * attivazione ed e' vuota. Finche' resta vuota `ARTICLE_SECTION_CORE` /
 * `ARTICLE_SECTION_CORE_LIST` contengono solo frontaliere e svizzera, quindi
 * nessun consumer che itera le sezioni cambia comportamento. Per accendere un
 * cantone si aggiunge il suo codice ad `ACTIVE_CANTON_CODES`, si rigenera e si
 * consegnano nella stessa PR le superfici che la sezione richiede (route del
 * Worker, pubblicazione R2, copy dell'archivio).
 *
 * Uso:
 *   node scripts/generate-canton-article-sections.mjs          # scrive il file
 *   node scripts/generate-canton-article-sections.mjs --check  # exit 1 se il file e' stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE_REL = 'data/canton-url-slugs.json';
export const OUTPUT_REL = 'packages/articles/engine/shared/cantonArticleSectionCore.generated.mjs';
export const GENERATED_MARKER = '// AUTO-GENERATED by scripts/generate-canton-article-sections.mjs — DO NOT EDIT BY HAND.';

/**
 * Lista di attivazione (codici di gruppo URL, es. `TI`, `BASILEA`). Vuota per
 * scelta: le sezioni cantonali entrano nella tabella senza cambiare l'output
 * di oggi. Ordine irrilevante: il generato la ordina come le voci.
 */
export const ACTIVE_CANTON_CODES = [];

const LOCALES = ['it', 'en', 'de', 'fr'];

/**
 * I 6 hub tematici figli diretti di ogni sezione cantonale, con slug
 * localizzati riservati (decisione D2 del piano sezioni cantonali). La chiave
 * e' l'id stabile del tema; i valori sono i segmenti URL per locale.
 */
export const CANTON_HUB_TOPICS = {
  carburanti: { it: 'carburanti', en: 'fuel', de: 'treibstoff', fr: 'carburants' },
  fisco: { it: 'fisco', en: 'tax', de: 'steuern', fr: 'fiscalite' },
  mobilita: { it: 'mobilita', en: 'mobility', de: 'mobilitaet', fr: 'mobilite' },
  eventi: { it: 'eventi', en: 'events', de: 'veranstaltungen', fr: 'evenements' },
  pensioni: { it: 'pensioni', en: 'pensions', de: 'renten', fr: 'retraites' },
  servizi: { it: 'servizi', en: 'services', de: 'dienstleistungen', fr: 'services' },
};

const SLUG_RX = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** `TI` → `canton-ti`, `BASILEA` → `canton-basilea`. */
export function cantonSectionId(code) {
  return `canton-${code.toLowerCase()}`;
}

/**
 * Costruisce le voci a partire dalla tabella `cantons` di
 * `data/canton-url-slugs.json`. Fallisce invece di indovinare: uno slug
 * mancante o non ASCII produrrebbe un URL pubblico sbagliato.
 */
export function buildCantonSectionEntries(slugTable) {
  const cantons = slugTable?.cantons;
  if (!cantons || typeof cantons !== 'object') {
    throw new Error(`${SOURCE_REL}: tabella "cantons" assente`);
  }
  const codes = Object.keys(cantons).sort();
  if (codes.length !== 24) {
    throw new Error(`${SOURCE_REL}: attesi 24 gruppi URL (22 cantoni + APPENZELLO + BASILEA), trovati ${codes.length}`);
  }
  return codes.map((code) => {
    const slugs = cantons[code];
    for (const locale of LOCALES) {
      const value = slugs?.[locale];
      if (typeof value !== 'string' || !SLUG_RX.test(value)) {
        throw new Error(`${SOURCE_REL}: slug ${locale} di ${code} non valido: ${JSON.stringify(value)}`);
      }
    }
    const section = cantonSectionId(code);
    const lower = code.toLowerCase();
    return {
      section,
      kind: 'canton',
      canton: code,
      indexSlug: {
        it: `articoli-${slugs.it}`,
        en: `${slugs.en}-articles`,
        de: `${slugs.de}-artikel`,
        fr: `articles-${slugs.fr}`,
      },
      bodyDir: `blog-body-canton-${lower}`,
      metaPrefix: `blog-meta-canton-${lower}`,
      // Sotto `packages/articles/content/`: nel sito e' la cartella reale del
      // corpus, nel corpus la mappa il PREFIX di `corpus-paths.mjs` su
      // `content/cantons/<section>/`, senza nuove voci EXACT.
      registryFile: `packages/articles/content/cantons/${section}/registry.ts`,
      slugDataFile: `packages/articles/content/cantons/${section}/slugs.ts`,
      slugConst: 'CANTON_SLUGS',
      // Nessuno shard Pages: le sezioni cantonali sono servite da R2 + Worker.
      shardKey: null,
    };
  });
}

const q = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function renderLocaleMap(map) {
  return `{ ${LOCALES.map((l) => `${l}: ${q(map[l])}`).join(', ')} }`;
}

/** Il sorgente completo del modulo generato. Puro: nessun I/O. */
export function renderCantonArticleSectionCore(slugTable, activeCodes = ACTIVE_CANTON_CODES) {
  const entries = buildCantonSectionEntries(slugTable);
  const known = new Set(entries.map((e) => e.canton));
  for (const code of activeCodes) {
    if (!known.has(code)) throw new Error(`ACTIVE_CANTON_CODES: codice sconosciuto ${JSON.stringify(code)}`);
  }
  const activeSet = new Set(activeCodes);
  const active = entries.filter((e) => activeSet.has(e.canton)).map((e) => e.section);

  const lines = [
    GENERATED_MARKER,
    `// Sorgente: ${SOURCE_REL} (tabella \`cantons\`).`,
    '// Rigenera: node scripts/generate-canton-article-sections.mjs',
    '// Verifica: node scripts/generate-canton-article-sections.mjs --check',
    '',
    '/**',
    ' * Sezioni articoli cantonali: una voce per gruppo URL (22 cantoni +',
    ' * APPENZELLO + BASILEA), stessa forma delle voci di `articleSectionCore.mjs`',
    " * piu' `canton` (codice di gruppo) e `topicHubs` (slug riservati dei 6 hub",
    ' * tematici). Modulo puro, senza import: lo carica `articleSectionCore.mjs`.',
    ' *',
    ' * Le voci sono dati: una sezione diventa attiva solo se il suo id compare',
    ' * in `ACTIVE_CANTON_SECTIONS`.',
    ' */',
    '',
    '/** Hub tematici di ogni sezione cantonale: id del tema -> slug per locale. */',
    'export const CANTON_HUB_TOPICS = {',
    ...Object.entries(CANTON_HUB_TOPICS).map(([key, slugs]) => `  ${key}: ${renderLocaleMap(slugs)},`),
    '};',
    '',
    '/** Ordine canonico dei temi. */',
    `export const CANTON_HUB_TOPIC_KEYS = [${Object.keys(CANTON_HUB_TOPICS).map(q).join(', ')}];`,
    '',
    '/** Voci cantonali per id di sezione, in ordine di codice. */',
    'export const CANTON_ARTICLE_SECTION_CORE = {',
  ];
  for (const e of entries) {
    lines.push(
      `  ${q(e.section)}: {`,
      `    section: ${q(e.section)},`,
      `    kind: ${q(e.kind)},`,
      `    canton: ${q(e.canton)},`,
      `    indexSlug: ${renderLocaleMap(e.indexSlug)},`,
      `    bodyDir: ${q(e.bodyDir)},`,
      `    metaPrefix: ${q(e.metaPrefix)},`,
      `    registryFile: ${q(e.registryFile)},`,
      `    slugDataFile: ${q(e.slugDataFile)},`,
      `    slugConst: ${q(e.slugConst)},`,
      '    shardKey: null,',
      '    topicHubs: CANTON_HUB_TOPICS,',
      '  },',
    );
  }
  lines.push(
    '};',
    '',
    '/** Lista di attivazione: id delle sezioni cantonali attive (vuota = nessuna). */',
    `export const ACTIVE_CANTON_SECTIONS = [${active.map(q).join(', ')}];`,
    '',
  );
  return lines.join('\n');
}

function main(argv) {
  const check = argv.includes('--check');
  const slugTable = JSON.parse(readFileSync(path.join(REPO_ROOT, SOURCE_REL), 'utf-8'));
  const expected = renderCantonArticleSectionCore(slugTable);
  const outPath = path.join(REPO_ROOT, OUTPUT_REL);
  let current = null;
  try {
    current = readFileSync(outPath, 'utf-8');
  } catch (err) {
    if (err?.code !== 'ENOENT') throw err;
  }
  if (check) {
    if (current !== expected) {
      console.error(`${OUTPUT_REL} non corrisponde a ${SOURCE_REL}: esegui node scripts/generate-canton-article-sections.mjs`);
      return 1;
    }
    console.log(`${OUTPUT_REL} aggiornato.`);
    return 0;
  }
  if (current === expected) {
    console.log(`${OUTPUT_REL} gia' aggiornato.`);
    return 0;
  }
  writeFileSync(outPath, expected);
  console.log(`scritto ${OUTPUT_REL}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
