#!/usr/bin/env node
/**
 * generate-profession-landing-routes.mjs
 *
 * Dumps the full, deterministic route list for the profession-canton
 * (`build-plugins/professionCantonData.ts`) and profession-city
 * (`build-plugins/professionCityData.ts`) landing families into
 * `data/profession-landing-routes.json`.
 *
 * WHY a generated snapshot instead of a live import. Both source modules
 * have extensionless relative imports (TS-bundler style, fine under Vite)
 * that Node's native type-stripping ESM loader can't resolve under plain
 * `node` (confirmed: `node -e "import('./build-plugins/professionCantonData.ts')"`
 * throws ERR_MODULE_NOT_FOUND on its `./professionLandingsData` import) —
 * but the audit classifiers that need this route set
 * (scripts/lib/professionLandingsSections.mjs) run under plain `node` in
 * CI (package.json `audit:*` scripts), not `tsx`. Both route lists are
 * fully static (enumerated from PROFESSION_IDS × cantons/cities × locales
 * — no live job data), so a one-time dump avoids both the resolver problem
 * AND a hand-duplicated place-token regex (which would need every canton
 * slug in every locale, several with internal hyphens like "san-gallo" —
 * exactly the drift class CLAUDE.md non-negotiable #6 warns about).
 *
 * Regenerate after any change to PROFESSION_IDS, PROFESSION_CANTON_KEYS,
 * PROFESSION_CITY_KEYS, or any of their slug tables:
 *   npx tsx scripts/generate-profession-landing-routes.mjs
 */
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROFESSION_CANTON_ROUTES } from '../build-plugins/professionCantonData.ts';
import { PROFESSION_CITY_ROUTES } from '../build-plugins/professionCityData.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'data/profession-landing-routes.json');

const payload = {
  generated: new Date().toISOString(),
  _comment: 'Generated by scripts/generate-profession-landing-routes.mjs — do not hand-edit. Regenerate after touching PROFESSION_IDS / PROFESSION_CANTON_KEYS / PROFESSION_CITY_KEYS or their slug tables.',
  professionCantonRoutes: PROFESSION_CANTON_ROUTES,
  professionCityRoutes: PROFESSION_CITY_ROUTES,
};

await writeFile(OUT, JSON.stringify(payload, null, 2) + '\n', 'utf8');
console.log(`wrote ${PROFESSION_CANTON_ROUTES.length} canton routes + ${PROFESSION_CITY_ROUTES.length} city routes -> ${OUT}`);
