/**
 * healthSectorWageBenchmark.ts — official wage reference for the
 * health-facility pages when the listings themselves are too thin.
 *
 * Why. The facility tile "Median of reported ranges" is computed only from
 * source-reported CHF ranges (≥ MIN_REPORTED_SALARY_SAMPLES). Hospital
 * listings almost never publish a range: on 2026-10-24, 109 of the 111 EN
 * facility pages in the sitemap rendered "Insufficient sample" (102 with zero
 * reported ranges). Falling back to the sector-estimated bands would be
 * circular, so the fallback is the BFS figure for the facility's own sector
 * and Grossregion — a measured, citable number, labelled as a benchmark.
 *
 * Source: BFS/OFS Swiss Earnings Structure Survey (LSE/RSS), STAT-TAB cube
 * px-x-0304010000_201 ("Monatlicher Bruttolohn nach Grossregion,
 * Wirtschaftsabteilung, beruflicher Stellung und Geschlecht"), division
 * NOGA 86 "Gesundheitswesen", all positions, both sexes. Values are the
 * standardised gross monthly wage (FTE, 4⅓ weeks × 40 h) and already include
 * 1/12 of the 13th salary and of annual bonuses, private and public sector
 * together — so the annual figure is exactly ×12.
 *
 * Every registry category (acute / rehab / psychiatry / birth / other) comes
 * from the BAG hospital list, i.e. NOGA 86.
 *
 * Literals, not a JSON import: the facility plugin sits in the Vite config
 * graph (same constraint as cantonSalaryIndex.ts). Refresh on each new LSE
 * wave with `node scripts/update-bfs-health-sector-wages.mjs` (it prints the
 * table and exits non-zero when these literals drift from STAT-TAB).
 */

