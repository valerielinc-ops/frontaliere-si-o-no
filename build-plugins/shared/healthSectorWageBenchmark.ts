export interface HealthSectorWageBenchmark {
  readonly region: Grossregion | 'switzerland';
  readonly waveYear: number;
  readonly monthly: MonthlyWageQuartiles;
  /** Annual gross CHF (×12: the LSE monthly already holds 1/12 of the 13th). */
  readonly annualMedianChf: number;
  readonly annualP25Chf: number;
  readonly annualP75Chf: number;
}

/**
 * BFS healthcare-sector wage quartiles for a canton code. Unknown or missing
 * cantons fall back to the Switzerland total rather than to nothing: the
 * figure is always the official one, only its geographic scope widens.
 */
export function healthSectorWageBenchmark(canton: string | null | undefined): HealthSectorWageBenchmark {
  const code = String(canton || '').trim().toUpperCase();
  const region: Grossregion | 'switzerland' = CANTON_TO_GROSSREGION[code] ?? 'switzerland';
  const monthly = HEALTH_SECTOR_MONTHLY_WAGES[region];
  return {
    region,
    waveYear: HEALTH_SECTOR_WAGE_SOURCE.waveYear,
    monthly,
    annualMedianChf: monthly.median * 12,
    annualP25Chf: monthly.p25 * 12,
    annualP75Chf: monthly.p75 * 12,
  };
}
