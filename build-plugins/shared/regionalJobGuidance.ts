function locality(job: RegionalJobRecord): string {
  return String(job.location || '').split(',')[0].trim();
}

function collectInventory(jobs: readonly RegionalJobRecord[], cityHubs: readonly RegionalCityHub[]) {
  const cityCounts = new Map<string, { name: string; count: number }>();
  const companyCounts = new Map<string, { name: string; count: number }>();

  for (const job of jobs) {
    const city = locality(job);
    const cityKey = normalizeCitySlug(city);
    if (city && cityKey) {
      const current = cityCounts.get(cityKey);
      if (current) current.count++;
      else cityCounts.set(cityKey, { name: city, count: 1 });
    }

    const company = String(job.company || '').trim();
    const companyKey = company.normalize('NFKC').toLocaleLowerCase();
    if (company && companyKey) {
      const current = companyCounts.get(companyKey);
      if (current) current.count++;
      else companyCounts.set(companyKey, { name: company, count: 1 });
    }
  }

  const hubsBySlug = new Map(cityHubs.map((hub) => [normalizeCitySlug(hub.slug), hub]));
  return {
    cities: [...cityCounts.entries()]
      .map(([slug, value]) => ({ ...value, slug, hub: hubsBySlug.get(slug) }))
      .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name))
      .slice(0, 6),
    companies: [...companyCounts.values()]
      .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name))
      .slice(0, 6),
  };
}

function renderSources(canton: RegionalGuidanceCanton, locale: RegionalLocale, copy: GuidanceCopy): string {
  const labels = SOURCE_LABEL[locale];
  const sources = OFFICIAL_SOURCES[canton]
    .map((source) => {
      const label = source.labelKey === 'job' ? copy.officialJobSearchLabel
        : source.labelKey === 'mobility' ? copy.mobilitySourceLabel
        : source.labelKey === 'mobilityNetwork' ? copy.mobilityNetworkSourceLabel || labels.mobilityNetwork
        : copy.languageSourceLabel || labels.language;
      return `<li><a href="${escapeHtml(source.href)}" rel="noopener noreferrer">${escapeHtml(label)}</a></li>`;
    });
  return `<h3 class="s-8S_vke">${escapeHtml(copy.sourceTitle)}</h3><ul class="s-N93mPe">${sources.join('')}</ul>`;
}

function renderInventory(
  opts: RegionalJobGuidanceOptions,
  copy: GuidanceCopy,
  inventory: ReturnType<typeof collectInventory>,
): string {
  if (opts.jobs.length === 0) {
    return `<p class="s-L9sOKI" data-regional-empty-inventory>${escapeHtml(copy.emptyInventory)}</p>`;
  }

  const cityBase = canonicalPath(opts.cityHubBaseHref);
  const cityItems = inventory.cities.map((city) => {
    const display = escapeHtml(city.hub?.label || city.name);
    const href = city.hub ? `${cityBase}${encodeURIComponent(city.hub.slug)}/` : '';
    const label = href ? `<a href="${escapeHtml(canonicalPath(href))}">${display}</a>` : display;
    return `<li>${label} · ${escapeHtml(copy.jobWord(city.count))}</li>`;
  });
  const companyItems = inventory.companies.map((company) =>
    `<li>${escapeHtml(company.name)} · ${escapeHtml(copy.jobWord(company.count))}</li>`,
  );
  const parts: string[] = [];
  if (cityItems.length > 0) {
    parts.push(`<div><h4 class="s-iZTOT1">${escapeHtml(copy.citiesTitle)}</h4><ul class="s-N93mPe">${cityItems.join('')}</ul></div>`);
  }
  if (companyItems.length > 0) {
    parts.push(`<div><h4 class="s-iZTOT1">${escapeHtml(copy.companiesTitle)}</h4><ul class="s-N93mPe">${companyItems.join('')}</ul></div>`);
  }
  return parts.length > 0 ? `<div data-regional-job-inventory>${parts.join('')}</div>` : '';
}

/**
 * Region-specific, source-linked guidance for the growth targets. Inventory
 * is derived only from the validated job inventory passed by jobsSeoPagesPlugin;
 * city links are restricted to the exact hubs that plugin emitted.
 */
export function renderRegionalJobGuidance(opts: RegionalJobGuidanceOptions): string {
  if (!isRegionalLocale(opts.locale)) return '';
  const locale = opts.locale;
  const key = regionalTargetKey(opts.canton, locale);
  if (!key || !isRegionalJobGuidanceTarget(opts.canton, locale)) return '';
  const copy = COPY[key];

  const count = opts.jobs.length;
  const inventory = collectInventory(opts.jobs, opts.cityHubs);
  const archiveHref = canonicalPath(opts.archiveHref);
  const faq = copy.faqs(opts.display)
    .map(({ question, answer }) => `<p class="s-F2hp6o"><strong>${escapeHtml(question)}</strong> ${escapeHtml(answer)}</p>`)
    .join('');
  const mobilitySource = OFFICIAL_SOURCES[opts.canton].find((source) => source.labelKey === 'mobility');
  const languageSource = OFFICIAL_SOURCES[opts.canton].find((source) => source.labelKey === 'language');
  const mobilityLinkLabel = copy.mobilitySourceLabel;
  const sourceLinks = renderSources(opts.canton, locale, copy);
  const nav = opts.archiveNavigationHtml || '';
  const archiveLink = `<p class="s-L9sOKI"><a class="s-7DS5hj" href="${escapeHtml(archiveHref)}">${escapeHtml(copy.archiveLabel)}</a></p>`;

  return `<section class="s-IE_H9o" data-canton-context-prose data-canton-editorial data-regional-job-guidance data-regional-canton="${opts.canton}" data-regional-locale="${opts.locale}">` +
    `${nav}<h2 class="s-h0yI7F">${escapeHtml(copy.heading)}</h2>` +
    `<p class="s-L9sOKI">${escapeHtml(copy.opening(opts.display, count))}</p>` +
    archiveLink +
    `<h3 class="s-8S_vke">${escapeHtml(copy.localTitle)}</h3><p class="s-L9sOKI">${escapeHtml(copy.localText)}</p>` +
    `<h3 class="s-8S_vke">${escapeHtml(copy.mobilityTitle)}</h3><p class="s-L9sOKI">${escapeHtml(copy.mobilityText)} ${mobilitySource ? `<a href="${escapeHtml(mobilitySource.href)}" rel="noopener noreferrer">${escapeHtml(mobilityLinkLabel)}</a>.` : ''}</p>` +
    renderInventory(opts, copy, inventory) +
    `<h3 class="s-8S_vke">${escapeHtml(copy.languageTitle)}</h3><p class="s-L9sOKI">${escapeHtml(copy.languageText)}${languageSource ? ` <a href="${escapeHtml(languageSource.href)}" rel="noopener noreferrer">${escapeHtml(copy.languageSourceLabel || SOURCE_LABEL[locale].language)}</a>.` : ''}</p>` +
    sourceLinks +
    `<details class="s-01GpQM"><summary class="s-qAjSfB">${locale === 'it' ? 'Domande frequenti sulla ricerca lavoro' : 'Questions fréquentes sur la recherche d’emploi'}</summary><div class="s-4vhLHi">${faq}</div></details>` +
    `</section>`;
}

