import type { HubLocale } from '../seoHubsData';

export type RegionalGuidanceCanton = 'GR' | 'GE' | 'VD' | 'NE';

export interface RegionalJobRecord {
  company?: string | null;
  location?: string | null;
}

export interface RegionalCityHub {
  slug: string;
  label: string;
}

export interface RegionalJobGuidanceOptions {
  canton: RegionalGuidanceCanton;
  locale: HubLocale;
  display: string;
  jobs: readonly RegionalJobRecord[];
  /** Canonical URL of the already-emitted canton archive, including trailing slash. */
  archiveHref: string;
  /** Canonical canton root used to build links to the already-emitted city hubs. */
  cityHubBaseHref: string;
  /** Exact city hubs emitted by jobsSeoPagesPlugin for this canton. */
  cityHubs: readonly RegionalCityHub[];
  /** Existing archive navigator, generated by cantonHubEditorial. */
  archiveNavigationHtml: string;
}

const REGIONAL_TARGETS: ReadonlySet<string> = new Set(['GR:it', 'GE:fr', 'VD:fr', 'NE:fr']);

export function isRegionalJobGuidanceTarget(canton: string, locale: HubLocale): canton is RegionalGuidanceCanton {
  return REGIONAL_TARGETS.has(`${String(canton).toUpperCase()}:${locale}`);
}

const escapeHtml = (value: unknown): string => String(value ?? '')
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')
  .replace(/'/g, '&#39;');

function canonicalPath(path: string): string {
  const trimmed = String(path || '').trim();
  if (!trimmed) return '/';
  const leading = trimmed.startsWith('/') ? trimmed : `/${trimmed}`;
  return leading.endsWith('/') ? leading : `${leading}/`;
}

